/**
 * Flexible Free/Local AI Client
 * One place constructs and executes calls to free/local AI models.
 * Supports:
 * - Google Gemini API (Free Tier: gemini-2.0-flash / gemini-1.5-flash)
 * - Local Ollama (http://localhost:11434 with models like qwen2.5-coder or llama3)
 */

export interface AiClientConfig {
  provider: "gemini" | "ollama" | "mock" | "none";
  apiKey?: string;
  baseUrl: string;
  model: string;
}

export interface GenerateResult {
  text: string;
  model: string;
  provider: "gemini" | "ollama" | "mock";
  durationMs: number;
}

export function getAiConfig(): AiClientConfig {
  const geminiKey = process.env.GEMINI_API_KEY?.trim();
  const ollamaUrl = process.env.OLLAMA_BASE_URL?.trim();
  const mockAi = process.env.MOCK_AI?.trim();

  if (mockAi === "true") {
    return {
      provider: "mock",
      baseUrl: "",
      model: "mock-model",
    };
  }

  // Priority 1: Gemini Free Tier API Key
  if (geminiKey && geminiKey !== "your_gemini_api_key_here") {
    return {
      provider: "gemini",
      apiKey: geminiKey,
      baseUrl: "https://generativelanguage.googleapis.com/v1beta",
      model: process.env.GEMINI_MODEL || "gemini-3.8-flash",
    };
  }

  // Priority 2: Local Ollama instance
  if (ollamaUrl) {
    return {
      provider: "ollama",
      baseUrl: ollamaUrl.replace(/\/+$/, ""),
      model: process.env.OLLAMA_MODEL || "qwen2.5-coder",
    };
  }

  return {
    provider: "none",
    baseUrl: "http://localhost:11434",
    model: "none",
  };
}

/**
 * Executes a prompt against the configured free or local AI model.
 */
export async function generateAiCompletion(prompt: string, systemPrompt?: string): Promise<GenerateResult> {
  const config = getAiConfig();
  const startTime = Date.now();

  if (config.provider === "mock") {
    return {
      text: `Mock explanation for test environment.\n\nKey components interact through deterministic dependencies without hallucinations.`,
      model: config.model,
      provider: "mock",
      durationMs: Date.now() - startTime,
    };
  }

  if (config.provider === "gemini") {
    const url = `${config.baseUrl}/models/${config.model}:generateContent?key=${config.apiKey}`;
    const payload = {
      contents: [
        {
          role: "user",
          parts: [{ text: prompt }],
        },
      ],
      systemInstruction: systemPrompt
        ? {
            parts: [{ text: systemPrompt }],
          }
        : undefined,
      generationConfig: {
        temperature: 0.2,
        maxOutputTokens: 1024,
      },
    };

    try {
      const res = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });

      if (!res.ok) {
        const errorText = await res.text();
        throw new Error(`Gemini API error (${res.status}): ${errorText}`);
      }

      const data = await res.json();
      const text =
        data.candidates?.[0]?.content?.parts?.[0]?.text ||
        "No explanation text generated by Gemini.";

      return {
        text,
        model: config.model,
        provider: "gemini",
        durationMs: Date.now() - startTime,
      };
    } catch (err) {
      throw new Error(`Failed to call Google Gemini API: ${err instanceof Error ? err.message : String(err)}`);
    }
  }

  if (config.provider === "ollama") {
    // Try Ollama native /api/generate endpoint first
    const url = `${config.baseUrl}/api/generate`;
    const fullPrompt = systemPrompt ? `${systemPrompt}\n\n${prompt}` : prompt;

    try {
      const res = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          model: config.model,
          prompt: fullPrompt,
          stream: false,
          options: {
            temperature: 0.2,
          },
        }),
      });

      if (!res.ok) {
        // Fallback to OpenAI-compatible chat completions endpoint if /api/generate failed
        const chatUrl = `${config.baseUrl}/v1/chat/completions`;
        const chatRes = await fetch(chatUrl, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            model: config.model,
            messages: [
              ...(systemPrompt ? [{ role: "system", content: systemPrompt }] : []),
              { role: "user", content: prompt },
            ],
            temperature: 0.2,
          }),
        });

        if (!chatRes.ok) {
          throw new Error(`Ollama returned status ${res.status}`);
        }

        const chatData = await chatRes.json();
        const text = chatData.choices?.[0]?.message?.content || "No explanation text generated by Ollama.";
        return {
          text,
          model: config.model,
          provider: "ollama",
          durationMs: Date.now() - startTime,
        };
      }

      const data = await res.json();
      const text = data.response || "No explanation text generated by Ollama.";

      return {
        text,
        model: config.model,
        provider: "ollama",
        durationMs: Date.now() - startTime,
      };
    } catch (err) {
      throw new Error(
        `Failed to reach local Ollama at ${config.baseUrl}. Make sure Ollama is running ('ollama run ${config.model}') or set GEMINI_API_KEY in .env.local: ${
          err instanceof Error ? err.message : String(err)
        }`,
      );
    }
  }

  throw new Error(
    "No AI provider configured. Please provide a valid GEMINI_API_KEY in .env.local or start Ollama locally at http://localhost:11434.",
  );
}
